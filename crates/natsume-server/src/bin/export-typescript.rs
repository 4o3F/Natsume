#[cfg(target_os = "linux")]
fn main() -> std::process::ExitCode {
    exporter::run()
}

#[cfg(not(target_os = "linux"))]
fn main() -> std::process::ExitCode {
    tracing_subscriber::fmt().with_target(false).init();
    tracing::error!("the Server TypeScript exporter requires Linux");
    std::process::ExitCode::FAILURE
}

#[cfg(target_os = "linux")]
mod exporter {
    use std::{
        ffi::OsString,
        fs,
        io::{self, Write as _},
        path::PathBuf,
        process::ExitCode,
    };

    // Link the Server library so Specta can collect its HTTP DTOs.
    use natsume_server as _;
    use snafu::Snafu;

    const DEFAULT_OUTPUT: &str = "web/src/api/generated/types.ts";
    const EXPORT_FAILURE_ID: &str = "NATSUME_TYPESCRIPT_EXPORT_FAILED";

    pub(super) fn run() -> ExitCode {
        if export(std::env::args_os().skip(1)).is_err() {
            let _write_result = writeln!(io::stderr().lock(), "{EXPORT_FAILURE_ID}");
            return ExitCode::FAILURE;
        }
        ExitCode::SUCCESS
    }

    fn export(args: impl IntoIterator<Item = OsString>) -> Result<(), ExportError> {
        let output_path = parse_output_path(args)?;
        let encoded = bindings().map_err(|_| ExportError::TypeFailed)?;
        fs::write(output_path, encoded).map_err(|_| ExportError::WriteFailed)
    }

    fn bindings() -> Result<String, specta_typescript::Error> {
        // PhasesFormat preserves conditional response fields such as the omitted
        // Binding evaluation. Integer metadata preserves the existing JSON numbers.
        specta_typescript::Typescript::default()
            .header("// Generated by export-typescript. Do not edit; run deno task api.\n")
            .export(&specta::collect(), specta_serde::PhasesFormat)
    }

    fn parse_output_path(args: impl IntoIterator<Item = OsString>) -> Result<PathBuf, ExportError> {
        let mut args = args.into_iter();
        let output_path = args
            .next()
            .unwrap_or_else(|| OsString::from(DEFAULT_OUTPUT));
        if args.next().is_some() {
            return Err(ExportError::InvalidArguments);
        }
        Ok(PathBuf::from(output_path))
    }

    #[derive(Debug, Clone, Copy, PartialEq, Eq, Snafu)]
    enum ExportError {
        #[snafu(display("the TypeScript exporter arguments are invalid"))]
        InvalidArguments,
        #[snafu(display("the HTTP types could not be exported"))]
        TypeFailed,
        #[snafu(display("the TypeScript bindings could not be written"))]
        WriteFailed,
    }

    #[cfg(test)]
    mod tests {
        use super::*;

        #[derive(specta::Type)]
        struct AutoCollected;

        #[test]
        fn collects_derived_types_without_a_registry() -> Result<(), specta_typescript::Error> {
            let output = bindings()?;
            for name in [
                "AutoCollected",
                "SessionResponse",
                "ImportPreviewResponse",
                "PrintRequest",
            ] {
                assert!(output.contains(&format!("export type {name} =")));
            }
            assert!(!output.contains("bigint"));
            Ok(())
        }

        #[test]
        fn default_output_is_the_web_bindings() -> Result<(), ExportError> {
            assert_eq!(parse_output_path([])?, PathBuf::from(DEFAULT_OUTPUT));
            Ok(())
        }

        #[test]
        fn exports_are_stable() -> Result<(), Box<dyn std::error::Error>> {
            let directory = tempfile::tempdir()?;
            let first = directory.path().join("first.ts");
            let second = directory.path().join("second.ts");
            export([first.clone().into_os_string()])?;
            export([second.clone().into_os_string()])?;
            let contents = fs::read(&first)?;
            assert_eq!(contents, fs::read(&second)?);
            assert!(contents.ends_with(b"\n"));
            Ok(())
        }

        #[test]
        fn invalid_arguments_are_closed_and_redacted() {
            let error = export(["output-path-canary".into(), "extra-argument-canary".into()]);
            assert_eq!(error, Err(ExportError::InvalidArguments));
            for message in [
                ExportError::InvalidArguments.to_string(),
                format!("{error:?}"),
            ] {
                assert!(!message.contains("canary"));
            }
        }

        #[test]
        fn write_failure_is_typed_and_redacted() -> Result<(), Box<dyn std::error::Error>> {
            let directory = tempfile::tempdir()?;
            assert_eq!(
                export([directory.path().into()]),
                Err(ExportError::WriteFailed)
            );
            assert_eq!(EXPORT_FAILURE_ID, "NATSUME_TYPESCRIPT_EXPORT_FAILED");
            Ok(())
        }
    }
}
